export function formatPhone(dial: string, local: string) {
  const digits = local.replace(/[^\d]/g, "").replace(/^0+/, "");
  const code = dial.replace(/[^\d]/g, "");
  if (!digits) return "";
  return `+${code} ${digits}`;
}
